// Generates the web's copies of the repo's voice files, which runs before
// dev, build, lint and the unit specs (package.json); the outputs are
// gitignored, so the web can never carry a stale copy:
//   src/generated/wags-voice.ts     from prompts/wags_voice.md, which Wags (here)
//                                   and the Morning Brief (workers/core/brief.py)
//                                   both speak from; e2e/wags-unit.spec.ts fails if
//                                   PERSONA stops containing it.
//   src/generated/arsenal-voice.ts  from prompts/arsenal_voice.md, which the pool
//                                   (workers/arsenal/pool.py) and Arm Me
//                                   (src/app/api/arsenal/arm) both write from;
//                                   e2e/arsenal-unit.spec.ts fails if the Arm Me
//                                   prompt stops containing it.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

/** The text sent to Claude (the header comment dropped) and its version. */
export function parseVoice(source, name = "prompts/wags_voice.md") {
  const body = source.replace(/^<!--[\s\S]*?-->\s*/, "");
  const m = body.match(/^VOICE_VERSION:\s*(\S+)\s*\n/);
  if (!m) throw new Error(`${name}: the first line after the comment must be VOICE_VERSION: <version>`);
  return { version: m[1], text: body.slice(m[0].length).trim() };
}

function generate(file, out, versionName, textName) {
  const raw = readFileSync(here(`../../../prompts/${file}`), "utf8").replace(/\r\n/g, "\n");
  const { version, text } = parseVoice(raw, `prompts/${file}`);
  writeFileSync(
    here(`../src/generated/${out}`),
    `// GENERATED by scripts/gen-voice.mjs from prompts/${file}. Do not edit.\n` +
      `export const ${versionName} = ${JSON.stringify(version)};\n` +
      `export const ${textName} = ${JSON.stringify(text)};\n`,
  );
}

mkdirSync(here("../src/generated"), { recursive: true });
generate("wags_voice.md", "wags-voice.ts", "VOICE_VERSION", "VOICE");
generate("arsenal_voice.md", "arsenal-voice.ts", "ARSENAL_VOICE_VERSION", "ARSENAL_VOICE");
