// Generates src/generated/wags-voice.ts from the repo's ONE voice file,
// prompts/wags_voice.md, which Wags (here) and the Morning Brief (workers/
// core/brief.py) both speak from. Runs before dev, build, lint and the unit
// specs (package.json); the output is gitignored, so the web can never carry
// a stale copy. e2e/wags-unit.spec.ts fails if PERSONA stops containing it.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const raw = readFileSync(here("../../../prompts/wags_voice.md"), "utf8").replace(/\r\n/g, "\n");

/** The text sent to Claude (the header comment dropped) and its version. */
export function parseVoice(source) {
  const body = source.replace(/^<!--[\s\S]*?-->\s*/, "");
  const m = body.match(/^VOICE_VERSION:\s*(\S+)\s*\n/);
  if (!m) throw new Error("prompts/wags_voice.md: the first line after the comment must be VOICE_VERSION: <version>");
  return { version: m[1], text: body.slice(m[0].length).trim() };
}

const { version, text } = parseVoice(raw);
mkdirSync(here("../src/generated"), { recursive: true });
writeFileSync(
  here("../src/generated/wags-voice.ts"),
  `// GENERATED by scripts/gen-voice.mjs from prompts/wags_voice.md. Do not edit.\n` +
    `export const VOICE_VERSION = ${JSON.stringify(version)};\n` +
    `export const VOICE = ${JSON.stringify(text)};\n`,
);
