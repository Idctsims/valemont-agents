// Generates src/generated/theme-colors.ts from src/styles/tokens.css, so the
// web manifest and the viewport theme-color carry the token values without a
// hex literal written by hand anywhere under src/.
//
// Runs before dev, build and lint (package.json). The output is gitignored
// and is the ONE file check:tokens exempts besides tokens.css: it is
// generated from tokens.css and cannot drift from it.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const css = readFileSync(root("src/styles/tokens.css"), "utf8");

export function themeBlock(source, theme) {
  const m = source.match(new RegExp(`\\[data-theme="${theme}"\\]\\s*\\{([^}]*)\\}`));
  if (!m) throw new Error(`no [data-theme="${theme}"] block in tokens.css`);
  const vars = {};
  for (const [, name, hex] of m[1].matchAll(/--vm-([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})/g)) {
    vars[name] = hex.toLowerCase();
  }
  return vars;
}

const pick = (vars, theme, names) =>
  Object.fromEntries(
    names.map((n) => {
      if (!vars[n]) throw new Error(`tokens.css: [data-theme="${theme}"] has no --vm-${n}`);
      return [n, vars[n]];
    }),
  );

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const night = pick(themeBlock(css, "night"), "night", ["bg", "accent", "wood"]);
  const day = pick(themeBlock(css, "day"), "day", ["bg"]);
  const out = `// GENERATED by scripts/gen-theme-colors.mjs from src/styles/tokens.css.
// Do not edit. Regenerated before every dev, build and lint run.
export const THEME_COLORS = ${JSON.stringify({ night, day }, null, 2)} as const;
`;
  mkdirSync(root("src/generated"), { recursive: true });
  writeFileSync(root("src/generated/theme-colors.ts"), out);
}
